export const DIFFICULTY_ORDER: GameDifficulty[] = ['story', 'standard', 'hardcore'];

export function getDifficultyProfile(diff?: GameDifficulty | string): DifficultyProfile {
  if (diff === 'story' || diff === 'hardcore') {
    return DIFFICULTY_PROFILES[diff];
  }
  return DIFFICULTY_PROFILES.standard;
}

export function buildDifficultyPrompt(diff?: GameDifficulty | string): string {
  const profile = getDifficultyProfile(diff);
  return profile.systemPromptRule;
}
